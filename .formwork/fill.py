with open(DOC, encoding='utf-8') as f:
    xml = f.read()

FONT = '<w:rFonts w:hint="eastAsia" w:ascii="\u5b8b\u4f53" w:hAnsi="\u5b8b\u4f53" w:eastAsia="\u5b8b\u4f53"/>'

def esc(t: str) -> str:
    """XML 文本转义（& 必须最先替换）"""
    return t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')

def cell_of(row_xml: str, j: int) -> str:
    """取行 XML 中的第 j 个单元格（<w:tc>；[ >] 避免误匹配 <w:tcPr>）"""
    return re.findall(r'<w:tc[ >].*?</w:tc>', row_xml, re.S)[j]

def replace_once(old: str, new: str, what: str) -> None:
    """在全文中替换一次；目标不存在时带说明地失败"""
    global xml
    assert old in xml, f'\u672a\u627e\u5230\u76ee\u6807: {what}'
    xml = xml.replace(old, new, 1)

def fill_value_cell(row_idx: int, cell_idx: int, text: str) -> None:
    """\u5728\u7a7a\u767d\u503c\u5355\u5143\u683c\u7684\u9996\u6bb5\u672b\u5c3e\u6ce8\u5165\u6587\u672c"""
    rows = re.findall(r'<w:tr[ >].*?</w:tr>', xml, re.S)
    cell = cell_of(rows[row_idx], cell_idx)
    run = f'<w:r><w:rPr>{FONT}<w:sz w:val="24"/><w:szCs w:val="24"/></w:rPr><w:t xml:space="preserve">{esc(text)}</w:t></w:r>'
    filled = cell.replace('</w:p>', run + '</w:p>', 1)
    replace_once(cell, filled, f'\u884c{row_idx}\u5355\u5143\u683c{cell_idx}')

def fill_long_cell(row_idx: int, cell_idx: int, sections: list) -> None:
    """
    \u957f\u6587\u672c\u5355\u5143\u683c\u5de5\u6574\u586b\u5199\uff1a
    \u4fdd\u7559\u9996\u6bb5\uff08\u6807\u9898\u6bb5\uff09\uff0c\u5220\u9664\u5176\u540e\u6240\u6709\u7a7a\u5360\u4f4d\u6bb5\uff0c
    \u7d27\u8d34\u6807\u9898\u63d2\u5165\u5206\u8282\u5185\u5bb9\uff08\u8282\u6807\u9898\u52a0\u7c97\uff0c\u6b63\u6587\u4e24\u5b57\u7f29\u8fdb\u3001\u4e24\u7aef\u5bf9\u9f50\u3001\u6bb5\u540e 60 \u7f29\u8fdb\u91cf\u884c\u8ddd\uff09
    """
    rows = re.findall(r'<w:tr[ >].*?</w:tr>', xml, re.S)
    cell = cell_of(rows[row_idx], cell_idx)
    paras = re.findall(r'<w:p[ >].*?</w:p>', cell, re.S)
    assert paras, '\u5355\u5143\u683c\u65e0\u6bb5\u843d'
    label = paras[0]

    def make_para(title: str, body: str) -> str:
        ppr = ('<w:pPr><w:spacing w:line="360" w:lineRule="auto" w:after="60"/>'
               '<w:ind w:firstLineChars="200" w:firstLine="480"/><w:jc w:val="both"/>'
               f'<w:rPr>{FONT}<w:sz w:val="24"/><w:szCs w:val="24"/></w:rPr></w:pPr>')
        bold = (f'<w:r><w:rPr>{FONT}<w:b/><w:sz w:val="24"/><w:szCs w:val="24"/></w:rPr>'
                f'<w:t xml:space="preserve">{esc(title)}</w:t></w:r>') if title else ''
        normal = (f'<w:r><w:rPr>{FONT}<w:sz w:val="24"/><w:szCs w:val="24"/></w:rPr>'
                  f'<w:t xml:space="preserve">{esc(body)}</w:t></w:r>')
        return f'<w:p>{ppr}{bold}{normal}</w:p>'

    content = ''.join(make_para(t, b) for t, b in sections)
    head = cell[:cell.find('<w:p')]
    filled = head + label + content + '</w:tc>'
    replace_once(cell, filled, f'\u884c{row_idx}\u5355\u5143\u683c{cell_idx}\u957f\u6587\u672c')

def check_box(row_idx: int, cell_idx: int, before_text: str, after: bool = False) -> None:
    """把 before_text 之前（或 after=True 时之后）最近的 Wingdings 空选框改为选中"""
    rows = re.findall(r'<w:tr[ >].*?</w:tr>', xml, re.S)
    cell = cell_of(rows[row_idx], cell_idx)
    sym = '<w:sym w:font="Wingdings" w:char="F0A8"/>'
    tpos = cell.find(esc(before_text))
    assert tpos >= 0, f'\u6587\u5b57\u672a\u627e\u5230: {before_text}'
    idx = cell.find(sym, tpos) if after else cell.rfind(sym, 0, tpos)
    assert idx >= 0, f'\u672a\u627e\u5230\u52fe\u9009\u6846: \u884c{row_idx}'
    checked = '<w:sym w:font="Wingdings" w:char="F0FE"/>'
    filled = cell[:idx] + checked + cell[idx + len(sym):]
    replace_once(cell, filled, f'\u884c{row_idx} \u52fe\u9009 {before_text}')

