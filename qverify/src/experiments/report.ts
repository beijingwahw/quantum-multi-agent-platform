/** Shared experiment reporting: deterministic JSON + Markdown pair in out/. */

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { pathToFileURL } from 'node:url';

/**
 * Entry-guard law (house form since batch 21), single-sourced for the five
 * experiment modules: a module renders ONLY when run directly
 * (`npm run exp:*`), never when imported — run-all.ts invokes the exported
 * mains instead. The caller MUST pass its own `import.meta.url` (the guard
 * compares it against process.argv[1]; this module's URL would never match).
 */
export function runIfMain(moduleUrl: string, main: () => void): void {
  if (moduleUrl === pathToFileURL(process.argv[1] ?? '').href) main();
}

export interface ReportContext {
  name: string;
  title: string;
}

export function writeReport(ctx: ReportContext, data: unknown, markdown: string): void {
  mkdirSync(dirname(`out/${ctx.name}.json`), { recursive: true });
  writeFileSync(`out/${ctx.name}.json`, JSON.stringify(data, null, 2) + '\n', 'utf8');
  writeFileSync(
    `out/${ctx.name}.md`,
    `# ${ctx.title}\n\n> Regenerated by \`npm run repro\`. Source: \`src/experiments/${ctx.name}.ts\`.\n\n${markdown}\n`,
    'utf8',
  );
  console.log(`wrote out/${ctx.name}.md`);
}

export function mdTable(headers: readonly string[], rows: ReadonlyArray<readonly string[]>): string {
  const head = `| ${headers.join(' | ')} |`;
  const sep = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((r) => `| ${r.join(' | ')} |`).join('\n');
  return [head, sep, body].join('\n');
}

export function fmt(x: number, digits = 6): string {
  return x.toFixed(digits);
}

export function sci(x: number, digits = 3): string {
  return x.toExponential(digits);
}
